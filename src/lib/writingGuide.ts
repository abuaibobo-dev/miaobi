/**
 * 写作技法注入系统 — 用提示词补偿小模型的写作质量
 */

// 写作圣经：强制要求的技法清单
export const WRITING_BIBLE = `

## 写作技法圣经（必须遵循）

### 感官描写（每段至少 2 种感官）
- 视觉：光影、色彩、构图、明暗对比
- 听觉：环境音、对话节奏、沉默的重量
- 触觉：温度、质感、力度、皮肤接触
- 嗅觉：空气中的气味、衣物的香气
- 味觉：唇齿间的味道、情绪的味道

### 节奏控制
- 紧张场景：短句、断句、省略号、破折号
- 抒情场景：长句、排比、通感
- 对话场景：穿插动作描写，不用"他说""她说"
- 转场：用感官细节过渡，不用"过了几天"

### 情感层次
- 表层：角色表现出来的
- 暗流：角色压抑的
- 读者能感知但角色自己不知道的
- 通过细节暗示，不用"他感到悲伤"

### 亲密场景写法（专业级）

#### 铺垫阶段（接触前）
- 环境暗示：灯光变暗、窗外雨声、钟表滴答、空调嗡鸣
- 身体信号：手指微颤、喉结滚动、视线躲闪又回来、无意识舔唇
- 空间压缩：两人距离从一米缩短到半米到十厘米，用物理距离映射心理距离
- 时间拉长：三秒钟的对视写成一段，用慢镜头感拉伸读者的期待

#### 接触阶段（渐进式）
- 先从最轻微的触碰开始：指尖碰手背、衣角擦过、呼吸喷在颈侧
- 每一次触碰都写角色的反应：退缩/靠近/颤抖/屏息
- 用温度变化标记升级：冰凉的指尖→温热的掌心→滚烫的皮肤
- 穿插内心独白：犹豫、自我警告、又放弃抵抗

#### 高潮阶段（最激烈时）
- 用短句+断句制造呼吸感："她的——""等等——""别停——"
- 用意象替代直接描写：潮汐/月光/火焰/丝绸/琴弦绷断
- 用身体反应暗示而非描写：弓起的背、抓紧床单的手指、无声的口型
- 用环境同步：窗外闪电/雨突然变大/蜡烛熄灭
- 用感官切换：从触觉切到听觉（心跳声）、切到嗅觉（汗水味）

#### 余韵阶段（结束后）
- 用物件暗示发生了什么：散落的衣物、凌乱的床单、窗台上的烟灰
- 用身体状态暗示：酸软的腿、被汗水打湿的头发、微红的脸颊
- 用沉默写满足：不说话，只是靠着，呼吸渐渐同步
- 用一个小动作收尾：手指划过对方的肩胛骨、轻轻咬耳朵、把被子拉过来盖住两人

#### 禁忌清单
- 不要直接描写器官名称
- 不要用"进入""插入"等动词
- 不要写成流水账式的动作记录
- 不要让角色在亲密时说大段对话
- 不要用"xxx代替"的偷懒写法

#### 高级技巧
- 多重叙事：同一场景，从不同角色的视角各写一段
- 错位叙事：写亲密场景的同时，穿插另一个时间线的回忆
- 留白叙事：用"后来的事不必细说"跳过最直白的部分，用前后的细节让读者自己补全
- 声音叙事：只写声音——呼吸、呢喃、布料摩擦、床架吱呀、窗外的雨

### 人物刻画
- 对话要有个人口癖和节奏
- 动作细节体现性格（紧张时咬指甲、自信时走路带风）
- 内心独白与外在表现的反差
- 用物件暗示关系（送的礼物、留下的痕迹）

### 环境氛围
- 天气映射情绪
- 光影暗示关系变化
- 季节与故事节奏同步
- 声音的远近暗示亲疏
`;

// 每章写完后提取的技法要点模板
export const TECHNIQUE_EXTRACTION_PROMPT = `
从刚才写的章节中，提取以下写作技法要点（JSON格式）：
{
  "sensoryDetails": ["本章用到的感官描写示例"],
  "rhythmPattern": "本章的节奏特点",
  "emotionalLayers": "本章的情感层次",
  "metaphors": ["本章使用的隐喻/意象"],
  "characterVoice": {"角色名": "对话特点"}
}
`;

// 续写时注入的技法引导
export function buildWritingPrompt(lastTechniques?: string): string {
  let prompt = WRITING_BIBLE;

  if (lastTechniques) {
    prompt += `\n\n## 上一章的技法参考\n${lastTechniques}\n\n请延续这些写作技法，保持风格一致。`;
  }

  prompt += `\n\n## 续写要求
1. 开头不要重复上一章结尾
2. 用一个新的感官细节切入
3. 对话穿插动作，不要连续对话超过 3 句不加描写
4. 每段至少一个具体的感官描写
5. 保持节奏：紧张→舒缓→紧张的波浪式推进
6. 结尾留一个钩子，让读者想看下一章`;

  return prompt;
}
